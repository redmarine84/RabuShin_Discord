CREATE TABLE IF NOT EXISTS public.discord_economy_shops
(
    shop_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    campaign_id UUID NOT NULL REFERENCES public.discord_campaigns(campaign_id) ON DELETE CASCADE,
    settlement_key TEXT NOT NULL,
    settlement_name TEXT NOT NULL,
    poi_key TEXT NOT NULL,
    shop_name TEXT NOT NULL,
    shop_kind TEXT NOT NULL,
    settlement_multiplier NUMERIC(6,3) NOT NULL DEFAULT 1.000,
    wealth_gp NUMERIC(12,2) NOT NULL DEFAULT 100.00 CHECK(wealth_gp >= 0),
    wealth_cap_gp NUMERIC(12,2) NOT NULL DEFAULT 100.00 CHECK(wealth_cap_gp > 0),
    restock_at TIMESTAMPTZ NOT NULL DEFAULT NOW() + INTERVAL '1 hour',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(campaign_id, settlement_key, poi_key)
);

CREATE TABLE IF NOT EXISTS public.discord_economy_stock
(
    stock_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id UUID NOT NULL REFERENCES public.discord_economy_shops(shop_id) ON DELETE CASCADE,
    item_key TEXT NOT NULL,
    item_name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Goods',
    rarity TEXT NOT NULL DEFAULT 'Common',
    value_class TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    base_price_gp NUMERIC(12,2) NOT NULL CHECK(base_price_gp >= 0),
    quantity INTEGER NOT NULL DEFAULT 0 CHECK(quantity >= 0),
    target_quantity INTEGER NOT NULL DEFAULT 1 CHECK(target_quantity > 0),
    condition_percent INTEGER NOT NULL DEFAULT 100 CHECK(condition_percent BETWEEN 0 AND 100),
    item_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_kind TEXT NOT NULL DEFAULT 'catalog' CHECK(source_kind IN ('catalog','resale')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(shop_id, item_key)
);

CREATE TABLE IF NOT EXISTS public.discord_item_condition
(
    inventory_item_id UUID PRIMARY KEY REFERENCES public.discord_inventory_items(inventory_item_id) ON DELETE CASCADE,
    condition_percent INTEGER NOT NULL DEFAULT 100 CHECK(condition_percent BETWEEN 0 AND 100),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.discord_economy_transactions
(
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id UUID NOT NULL REFERENCES public.discord_campaigns(campaign_id) ON DELETE CASCADE,
    shop_id UUID NOT NULL REFERENCES public.discord_economy_shops(shop_id) ON DELETE CASCADE,
    character_id UUID NOT NULL REFERENCES public.discord_characters(character_id) ON DELETE CASCADE,
    transaction_kind TEXT NOT NULL,
    item_name TEXT NOT NULL DEFAULT '',
    quantity INTEGER NOT NULL DEFAULT 1,
    unit_price_gp NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_gp NUMERIC(12,2) NOT NULL DEFAULT 0,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.discord_blacksmith_orders
(
    order_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    campaign_id UUID NOT NULL REFERENCES public.discord_campaigns(campaign_id) ON DELETE CASCADE,
    shop_id UUID NOT NULL REFERENCES public.discord_economy_shops(shop_id) ON DELETE CASCADE,
    character_id UUID NOT NULL REFERENCES public.discord_characters(character_id) ON DELETE CASCADE,
    item_name TEXT NOT NULL,
    item_description TEXT NOT NULL DEFAULT '',
    item_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    price_gp NUMERIC(12,2) NOT NULL CHECK(price_gp >= 0),
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','ready','completed','cancelled')),
    ready_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_discord_economy_stock_shop
ON public.discord_economy_stock(shop_id, category, item_name);

CREATE INDEX IF NOT EXISTS ix_discord_economy_transactions_character
ON public.discord_economy_transactions(character_id, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_discord_blacksmith_orders_character
