    tool_keywords JSONB NOT NULL DEFAULT '[]'::jsonb,
    tool_required BOOLEAN NOT NULL DEFAULT FALSE,
    required_container_family TEXT NOT NULL DEFAULT '',
    spoils_at TIMESTAMPTZ NULL,
    item_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(harvest_source_id,item_name)
);

